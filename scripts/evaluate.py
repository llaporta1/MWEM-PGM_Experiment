# computes L1 errors between real vs synthetic data 
import pandas as pd, numpy as np

real = pd.read_csv("../data/dataset_reduced.csv") # true datatset after DP heavy hitter step (rare ZIPs replaced w OTHER)
syn  = pd.read_csv("../results/synthetic.csv") # syntehtic dataset generated by MWEM + PGM 

def l1_error(df1, df2, cols): # helper function to compute L1 error for given set of cols (a marginal like ZIP_reduced, Age_bin)
    r = df1.groupby(cols).size() 
    s = df2.groupby(cols).size() # two lines groups real and synethic data by chosen colums, .size() counts how many rows fall into each unique combo of values (so we get two count tables)
    idx = r.index.union(s.index) # ensure inclusion of all possible combos that appear in either dataset (so if ZIP-age combo never appeared in real data, you still compare it)
    r, s = r.reindex(idx, fill_value=0), s.reindex(idx, fill_value=0) # realign both series on same index (union) and fill any missing counts w 0
    r, s = r/r.sum(), s/s.sum() # nromalize counts to probailities so total mass = 1
    return np.abs(r - s).sum() # sum of absolute differences between normalized counts
# i.e.: 0 = identical distributions; 1 = no overlap at all

marginals = [
    ("ZIP_reduced",),
    ("ZIP_reduced","Age_bin"),
    ("ZIP_reduced","Income_bin"),
    ("ZIP_reduced","Age_bin","Category"),
] # this is the workload - marginasl we care abt (workload we gave MWEM+PGM)

errs = [l1_error(real, syn, m) for m in marginals] # loop thru each marginal and call l1_error and store result in list
for m,e in zip(marginals, errs):
    print(f"{m}: L1 = {e:.4f}")
print(f"Mean L1 Error = {np.mean(errs):.4f}") # find mean L1 error across all marginals
